class TicketModel {
  final int? id;
  final String userId;
  final int eventId;
  final String status; // 'active', 'pending', 'used', 'cancelled'
  final String? passCode; // UUID auto-generated by DB, nullable since not returned at insert time

  TicketModel({this.id, required this.userId, required this.eventId, required this.status, this.passCode});

  factory TicketModel.fromJson(Map<String, dynamic> json) => TicketModel(
    id: json['id'],
    userId: json['user_id'],
    eventId: json['event_id'],
    status: json['status'],
    passCode: json['pass_code'],
  );

  Map<String, dynamic> toMap() => {
    'event_id': eventId,
    'status': status,
    // pass_code and user_id are auto-generated by DB defaults (gen_random_uuid / auth.uid)
  };
}